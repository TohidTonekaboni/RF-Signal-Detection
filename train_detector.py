"""Train a YOLO detector on the spectrogram images (time-frequency boxes, one class per modulation family).

    python train_detector.py                                  # YOLO26-nano from scratch, 40 epochs
    python train_detector.py --model yolo26s.yaml --epochs 60 # larger model
    python train_detector.py --single-class                   # one class "signal": boxes only, use with the classifier (two-stage); out = runs/detector_1cls
    python train_detector.py --time-scale 2                   # repeat every frame 2x so the 128-frame images become 256 rows (finer time grid)
    python train_detector.py --max-scenes 300 --epochs 2      # quick smoke run

The images are the 128 x 1024 spectrograms as grayscale PNG (-10..40 dB -> 0..255), the same convention as the YOLO export of
01_create_dataset.ipynb. They are rebuilt here from the dataset shards, in shuffled order, into <out>/data (done once).
Augmentation is limited to a frequency mirror and extra noise power (--noise-prob): scale, translation, mosaic and colour changes
would alter bandwidths, burst times and levels, which are the labels. Added noise lowers the SNR but moves no box edge.
Training stops after --patience epochs without a better fitness (default 15; the val box loss rises after its minimum).

Uses train and val only. The frozen test sets are evaluated once, in Evaluation.ipynb.
Outputs in --out (default runs/detector): best.pt, meta.json, metrics_val.json, train/ (Ultralytics logs and weights), val/ (confusion
matrix and PR curves of best.pt). diagnose_detector.py breaks the box quality down by SNR, family and box size.
Requires a recent Ultralytics release that includes YOLO26: pip install -U ultralytics
YOLO26 is end-to-end (NMS-free), so the iou argument of predict() has no effect on it.
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import numpy as np

from spectrum_common import (FAMILIES, N_FFT, N_FRAMES, PROJECT_DIR, SetReader, db_to_gray, find_dataset_root, gray_to_db, save_json,
                             set_seed)

try:
    from ultralytics.data.dataset import YOLODataset as _YOLODataset
except ImportError:                                          # ultralytics missing: only training and Detector need it
    _YOLODataset = object

IMGSZ = 1024


# =============================================================== YOLO dataset built from the shards
def build_yolo_dataset(root, out_dir, single_class=False, max_scenes=None, sets=("train", "val"), seed=0, time_scale=1, log=print):
    """Write <out_dir>/<set>/{images,labels} and data.yaml. Returns the path of data.yaml. Skipped if already built with the same settings.
    time_scale repeats every frame that many times (image height 128 * time_scale); the normalised labels do not change."""
    from PIL import Image
    out_dir = Path(out_dir)
    key = dict(root=str(root), single_class=single_class, max_scenes=max_scenes, sets=list(sets), seed=seed)
    if time_scale != 1:
        key["time_scale"] = time_scale                      # absent for 1: datasets built before this option stay valid
    marker = out_dir / "_built.json"
    if marker.exists():
        if json.loads(marker.read_text()) == key:
            return out_dir / "data.yaml"
        shutil.rmtree(out_dir)                              # generated by this script (the marker proves it): rebuild
    rng = np.random.default_rng(seed)
    for s in sets:
        reader = SetReader(root, s, max_scenes)
        order = rng.permutation(len(reader)) if s == "train" else np.arange(len(reader))   # shuffled names: batches mix sessions
        (out_dir / s / "images").mkdir(parents=True, exist_ok=True)
        (out_dir / s / "labels").mkdir(parents=True, exist_ok=True)
        for rank, i in enumerate(order):
            name = f"{rank:06d}_{reader.scenes.iloc[int(i)]['scene_id']}"
            Image.fromarray(np.repeat(db_to_gray(reader.spec_db(int(i))), time_scale, axis=0)).save(out_dir / s / "images" / f"{name}.png")
            lines = []
            for b in reader.boxes(int(i)).itertuples():
                if b.family_id > len(FAMILIES):
                    continue                                # held-out classes carry no training label
                w, h = b.box_x1 - b.box_x0 + 1, b.box_y1 - b.box_y0 + 1
                lines.append(f"{0 if single_class else b.family_id - 1} {(b.box_x0 + w / 2) / N_FFT:.6f} {(b.box_y0 + h / 2) / N_FRAMES:.6f} "
                             f"{w / N_FFT:.6f} {h / N_FRAMES:.6f}")
            (out_dir / s / "labels" / f"{name}.txt").write_text("\n".join(lines) + ("\n" if lines else ""))
        log(f"wrote {len(reader)} {s} images to {out_dir / s}")
    names = ["signal"] if single_class else FAMILIES
    (out_dir / "data.yaml").write_text(f"path: {out_dir.resolve()}\ntrain: train/images\nval: val/images\nnames:\n"
                                       + "".join(f"  {i}: {n}\n" for i, n in enumerate(names)))
    marker.write_text(json.dumps(key))
    return out_dir / "data.yaml"


def ultra_device(name="auto"):
    """Ultralytics device string: '0' (first CUDA GPU), 'mps' or 'cpu'."""
    if name != "auto":
        return name
    import torch
    if torch.cuda.is_available():
        return "0"
    if torch.backends.mps.is_available():
        return "mps"
    return "cpu"


# =============================================================== inference wrapper (used by Evaluation.ipynb)
class Detector:
    """Wraps a trained YOLO model. detect(db) -> [dict(box=(x0, y0, x1, y1) inclusive bins/frames, score, cls)], cls = family index or 0 (single class)."""

    def __init__(self, weights, device="auto", conf=0.05, iou=0.5):
        from ultralytics import YOLO
        weights = Path(weights)
        self.model = YOLO(str(weights))
        meta = weights.parent / "meta.json"
        info = json.loads(meta.read_text()) if meta.exists() else {}
        self.single_class = info.get("single_class", len(self.model.names) == 1)
        self.time_scale = int(info.get("time_scale", 1))
        self.imgsz = int(info.get("imgsz", IMGSZ))             # models trained before --imgsz have 1024 in meta.json or no meta at all
        self.conf, self.iou, self.device = conf, iou, ultra_device(device)

    def detect_batch(self, dbs, conf=None, batch=32):
        out = []
        for s in range(0, len(dbs), batch):
            ts = self.time_scale
            imgs = [np.repeat(np.repeat(db_to_gray(d), ts, axis=0)[:, :, None], 3, axis=2) for d in dbs[s:s + batch]]
            for r in self.model.predict(imgs, imgsz=self.imgsz, conf=self.conf if conf is None else conf, iou=self.iou, max_det=50,
                                        device=self.device, verbose=False):
                res = []
                for (xa, ya, xb, yb), c, k in zip(r.boxes.xyxy.cpu().numpy(), r.boxes.conf.cpu().numpy(), r.boxes.cls.cpu().numpy()):
                    x0 = int(np.clip(round(xa), 0, N_FFT - 1))
                    y0 = int(np.clip(round(ya / ts), 0, N_FRAMES - 1))
                    res.append(dict(box=(x0, y0, int(np.clip(round(xb) - 1, x0, N_FFT - 1)), int(np.clip(round(yb / ts) - 1, y0, N_FRAMES - 1))),
                                    score=float(c), cls=int(k)))
                out.append(res)
        return out

    def detect(self, db, conf=None):
        return self.detect_batch([db], conf)[0]


# =============================================================== training
class NoiseDataset(_YOLODataset):
    """Training dataset that adds extra noise power to an image with probability noise_prob (set by noise_trainer). The noise is drawn per
    original frame (and repeated time_scale times), like the noise of a real spectrogram. Boxes do not move. Module level: workers pickle it."""
    noise_prob, time_scale, rng = 0.0, 1, None

    def get_image_and_label(self, index):
        label = super().get_image_and_label(index)
        if self.rng is None:
            self.rng = np.random.default_rng()               # created inside the worker process: independent streams
        if self.rng.random() < self.noise_prob:
            img = label["img"]                               # H x W x 3 uint8; may be shared with the image buffer: do not edit in place
            ts = self.time_scale
            noise = np.repeat(self.rng.exponential(self.rng.uniform(0.05, 0.5), (img.shape[0] // ts, img.shape[1])), ts, axis=0)
            label["img"] = db_to_gray(10.0 * np.log10(10.0 ** (gray_to_db(img) / 10.0) + noise[:, :, None]))
        return label


def noise_trainer(prob, time_scale=1):
    """Ultralytics trainer whose training images get extra noise power (val images stay untouched)."""
    from ultralytics.models.yolo.detect import DetectionTrainer

    class NoiseTrainer(DetectionTrainer):
        def build_dataset(self, img_path, mode="train", batch=None):
            ds = super().build_dataset(img_path, mode, batch)
            if mode == "train":
                ds.__class__, ds.noise_prob, ds.time_scale = NoiseDataset, prob, time_scale
            return ds

    return NoiseTrainer


def train(a):
    from ultralytics import YOLO
    set_seed(a.seed)
    root = find_dataset_root(a.root)
    out = Path(a.out or PROJECT_DIR / "runs" / ("detector_1cls" if a.single_class else "detector")).resolve()   # absolute: Ultralytics re-roots relative project paths under its runs_dir. The names Evaluation.ipynb looks for
    out.mkdir(parents=True, exist_ok=True)
    data = build_yolo_dataset(root, out / "data", a.single_class, a.max_scenes, seed=a.seed, time_scale=a.time_scale)
    if a.prepare_only:
        print("dataset ready:", data)
        return
    device = ultra_device(a.device)
    print(f"model={a.model}  device={device}  single_class={a.single_class}  data={data}")
    model = YOLO(a.model)
    model.train(
        trainer=noise_trainer(a.noise_prob, a.time_scale) if a.noise_prob > 0 else None,
        data=str(data), epochs=a.epochs, imgsz=a.imgsz, rect=True, batch=a.batch, device=device, workers=a.workers,
        project=str(out), name="train", exist_ok=True, seed=a.seed, patience=a.patience or 100, cos_lr=True, plots=False,
        box=a.box, cls=a.cls, optimizer=a.optimizer, lr0=a.lr0, warmup_epochs=a.warmup_epochs, freeze=a.freeze,
        # only a frequency mirror: scale / translate / mosaic / colour would change the bandwidths, times and levels being labelled
        fliplr=0.5, flipud=0.0, mosaic=0.0, mixup=0.0, copy_paste=0.0, close_mosaic=0, scale=0.0, translate=0.0, degrees=0.0, shear=0.0,
        perspective=0.0, hsv_h=0.0, hsv_s=0.0, hsv_v=0.0, erasing=0.0)
    best = out / "train" / "weights" / "best.pt"
    shutil.copy(best, out / "best.pt")
    save_json(dict(single_class=a.single_class, classes=["signal"] if a.single_class else FAMILIES, imgsz=a.imgsz, model=a.model,
                   epochs=a.epochs, time_scale=a.time_scale, noise_prob=a.noise_prob), out / "meta.json")
    m = YOLO(str(out / "best.pt")).val(data=str(data), split="val", imgsz=a.imgsz, rect=True, batch=a.batch, device=device, plots=True, verbose=False,
                                       project=str(out), name="val", exist_ok=True)
    metrics = dict(map50=float(m.box.map50), map50_95=float(m.box.map), precision=float(m.box.mp), recall=float(m.box.mr))
    save_json(metrics, out / "metrics_val.json")
    print("validation (best.pt):", metrics)
    print("saved to", out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=None, help="dataset folder (default: newest in ./dataset)")
    ap.add_argument("--out", default=None, help="output folder (default: runs/detector, or runs/detector_1cls with --single-class)")
    ap.add_argument("--model", default="yolo26n.yaml", help="yolo26n.yaml (scratch) | yolo26s.yaml | yolo26m.yaml | yolo26n.pt / yolo26s.pt (COCO-pretrained, download: usually converge faster than scratch)")
    ap.add_argument("--epochs", type=int, default=40)
    ap.add_argument("--batch", type=int, default=16)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--device", default="auto", help="auto | 0 (cuda) | mps | cpu")
    ap.add_argument("--single-class", action="store_true", help="one class 'signal' instead of the 6 families (two-stage pipeline)")
    ap.add_argument("--patience", type=int, default=15, help="early stopping patience in epochs (0 = Ultralytics default of 100)")
    ap.add_argument("--noise-prob", type=float, default=0.5, help="probability of adding extra noise power to a training image (0 = off)")
    ap.add_argument("--imgsz", type=int, default=IMGSZ, help="network input size (long side, the frequency axis): >1024 upsamples the 1024-bin spectrogram, more pixels for narrow signals (slower, more memory)")
    ap.add_argument("--time-scale", type=int, default=1, help="repeat each frame N times: image height 128*N, finer grid on the time axis")
    ap.add_argument("--box", type=float, default=7.5, help="box loss gain (Ultralytics default 7.5)")
    ap.add_argument("--cls", type=float, default=0.5, help="classification loss gain (Ultralytics default 0.5)")
    ap.add_argument("--optimizer", default="auto", help="auto | AdamW | SGD ... ('auto' ignores --lr0 and picks its own rate)")
    ap.add_argument("--lr0", type=float, default=0.01, help="initial learning rate (only used with an explicit --optimizer; fine-tuning pretrained weights: ~0.0005 with AdamW)")
    ap.add_argument("--warmup-epochs", type=float, default=3.0, help="learning-rate warmup epochs (Ultralytics default 3)")
    ap.add_argument("--freeze", type=int, default=None, help="freeze the first N layers (10 = YOLO backbone), train only the head")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max-scenes", type=int, default=None, help="use only the first N scenes of train and val (smoke test)")
    ap.add_argument("--prepare-only", action="store_true", help="only build the YOLO image/label folders")
    train(ap.parse_args())


if __name__ == "__main__":
    main()
